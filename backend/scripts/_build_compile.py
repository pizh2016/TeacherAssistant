def _compile_dir(python_exe: Path, target: Path, label: str) -> bool:
    """Compile all .py files in a directory to .pyc (legacy mode)."""
    py_count = sum(1 for _ in target.rglob("*.py"))
    if py_count == 0:
        logger.info("No .py files in %s, skipping compile", label)
        return True

    logger.info("Compiling %d .py files in %s -> .pyc (legacy) ...",
                py_count, label)

    script = f"""\
import compileall, sys
success = compileall.compile_dir(
    r'{target}',
    maxlevels=50, quiet=1, force=True,
    optimize=0, legacy=True, workers=10,
)
sys.exit(0 if success else 1)
"""
    t0 = time.monotonic()
    result = subprocess.run(
        [str(python_exe), "-I", "-c", script],
        capture_output=True, text=True, check=False,
    )
    elapsed = time.monotonic() - t0

    if result.returncode != 0:
        logger.warning("%s compile failed (%.1fs): %s",
                       label, elapsed, result.stderr.strip())
        return False
    else:
        logger.info("Compiled %d files in %s (%.1fs)", py_count, label, elapsed)
        return True


def _smart_strip_source_files(pythonenv: Path) -> None:
    """Remove .py source files ONLY where a corresponding .pyc exists."""
    logger.info("Smart-stripping .py source files (only where .pyc exists) ...")
    removed = 0
    kept = 0
    for py_file in pythonenv.rglob("*.py"):
        pyc_file = py_file.with_suffix(".pyc")
        if pyc_file.exists():
            py_file.unlink()
            removed += 1
        else:
            kept += 1

    logger.info("Smart strip: removed %d .py, kept %d .py (no .pyc)", removed, kept)


def _cleanup_empty_pycache(pythonenv: Path) -> None:
    """Remove empty __pycache__ directories."""
    removed = 0
    for pycache in pythonenv.rglob("__pycache__"):
        if pycache.is_dir():
            try:
                contents = list(pycache.iterdir())
                if not contents:
                    pycache.rmdir()
                    removed += 1
            except OSError:
                pass
    logger.info("Cleaned up %d empty __pycache__ directories", removed)
