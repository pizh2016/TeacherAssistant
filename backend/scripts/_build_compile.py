"""Compile project source (src/horn/) into pythonenv.

This module runs on EVERY build (no smart skip) to guarantee that source
changes under src/horn/ are always reflected in
runtime/pythonenv/Lib/site-packages/horn/, even when the environment-level
smart skip reuses an existing pythonenv.

Steps (always executed):
  1. Pre-compile src/horn/ .py -> .pyc (legacy), then build wheel via
     the .venv interpreter. The wheel is installed into pythonenv
     (--no-deps --force-reinstall).
  2. Compile any remaining .py in site-packages/horn/ -> .pyc (safety net)
  3. Strip .py source files where a matching .pyc exists
  4. Clean __pycache__ inside site-packages/horn/
  5. Trim project .dist-info metadata regenerated by pip
  6. Clean Scripts/ directory regenerated by pip install (preserving pip executables)

Phase 2 (optional):
  compile_and_strip() compiles ALL of site-packages + stdlib .py -> .pyc,
  then smart-strips .py where .pyc exists. This is the optional deep compile.
"""

from __future__ import annotations

import logging
import os
import shutil
import subprocess
import tempfile
import time
import zipfile
from pathlib import Path

from _build_shared import BuildContext, _run_pip_stream

logger = logging.getLogger(__name__)


def compile_horn_source(ctx: BuildContext) -> None:
    """Reinstall and recompile project source into pythonenv.

    Ensures the latest src/horn/ code is always present in
    runtime/pythonenv/Lib/site-packages/horn/ as compiled .pyc bytecode.
    """
    logger.info("=" * 60)
    logger.info("Recompile project source (src/horn/ -> pythonenv)")
    logger.info("=" * 60)

    python_exe = ctx.pythonenv_python
    if not python_exe.exists():
        raise RuntimeError(
            f"pythonenv python.exe not found: {python_exe}\n"
            "Run phase 1 first: python scripts/build_runtime.py"
        )

    sp = ctx.pythonenv_site_packages
    horn_dir = sp / "horn"

    # Step 1: Rebuild wheel (.venv) and reinstall into pythonenv
    _force_reinstall_project(ctx)

    if not horn_dir.exists():
        raise RuntimeError(
            f"Project package 'horn' not found after install: {horn_dir}"
        )

    # Step 2: Compile horn/ .py -> .pyc (legacy, force)
    ok = _compile_horn_dir(python_exe, horn_dir)
    if not ok:
        raise RuntimeError("horn source compilation failed")

    # Step 3: Strip .py sources where .pyc exists (conservative)
    _strip_horn_sources(horn_dir)

    # Step 4: Clean __pycache__ inside horn/
    _clean_horn_pycache(horn_dir)

    # Step 5: Trim project metadata regenerated by pip install
    _trim_project_metadata(sp)

    # Step 6: Remove Scripts/ regenerated by pip install
    _clean_scripts_dir(ctx)

    pyc_count = sum(1 for _ in horn_dir.rglob("*.pyc"))
    logger.info(
        "Project source recompiled: %d .pyc in site-packages/horn/",
        pyc_count,
    )


def compile_and_strip(ctx: BuildContext, *, force: bool = False) -> bool:
    """Phase 2: Compile .py -> .pyc and slim the runtime environment.

    Compile strategy:
      1. Compile site-packages/ first (biggest space savings)
      2. Compile Lib/ stdlib (encodings .py files are protected)
      3. Smart strip: delete .py ONLY where .pyc exists alongside it
      4. Clean empty __pycache__ directories

    Returns:
        True if compile succeeded (or was skipped), False otherwise.
    """
    logger.info("=" * 60)
    logger.info("Phase 2: Compile .py -> .pyc and slim")
    logger.info("=" * 60)

    pythonenv = ctx.pythonenv_dir
    python_exe = ctx.pythonenv_python

    if not python_exe.exists():
        raise RuntimeError(
            f"pythonenv python.exe not found: {python_exe}\n"
            "Run phase 1 first: python scripts/build_runtime.py"
        )

    # Step 1: Compile site-packages
    sp = ctx.pythonenv_site_packages
    if sp.exists():
        sp_ok = _compile_dir(python_exe, sp, "site-packages")
        if not sp_ok:
            logger.warning("site-packages compile failed - aborting phase 2")
            return False

    # Step 2: Compile stdlib (Lib/)
    lib_dir = pythonenv / "Lib"
    if lib_dir.exists():
        lib_ok = _compile_dir(python_exe, lib_dir, "Lib (stdlib)")
        if not lib_ok:
            logger.warning("Lib compile failed - aborting phase 2")
            return False

    # Step 3: Smart strip
    _smart_strip_source_files(pythonenv)

    # Step 4: Clean empty __pycache__
    _cleanup_empty_pycache(pythonenv)

    logger.info("Phase 2 complete: compiled and slimmed")
    return True


