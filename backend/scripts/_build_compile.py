def _force_reinstall_project(ctx: BuildContext) -> None:
    """Rebuild the project wheel via .venv and install it into pythonenv."""
    src_horn = ctx.backend_root / "src" / "horn"

    # Step 1a: Clean __pycache__ from src/
    _clean_horn_pycache(src_horn)

    # Step 1b: Pre-compile src/horn/ .py -> .pyc (so wheel ships .pyc)
    _precompile_src_horn(ctx.venv_python, src_horn)

    # Step 1c: Build wheel with .venv python
    wheel_dir = ctx.cache_dir / "horn_wheel"
    if wheel_dir.exists():
        shutil.rmtree(wheel_dir)
    wheel_dir.mkdir(parents=True, exist_ok=True)

    logger.info("Building project wheel via .venv ...")
    cmd = [
        str(ctx.venv_python), "-I", "-m", "pip", "wheel",
        "--no-cache-dir", "--no-deps", "--progress-bar=off",
        "-w", str(wheel_dir),
    ] + ctx.pip_mirror_args + [str(ctx.backend_root)]
    rc = _run_pip_stream(cmd, "horn (build wheel)")
    if rc != 0:
        raise RuntimeError(f"Project wheel build failed (exit code {rc})")

    wheels = sorted(wheel_dir.glob("*.whl"), key=lambda p: p.stat().st_mtime)
    if not wheels:
        raise RuntimeError(f"No wheel produced in {wheel_dir}")
    wheel_file = wheels[-1]
    logger.info("Wheel built: %s", wheel_file.name)

    # Step 1d: Strip __pycache__ from wheel
    _strip_pycache_from_wheel(wheel_file)

    # Step 1e: Clean .pyc from source tree
    _clean_src_pyc(src_horn)
    _clean_horn_pycache(src_horn)

    # Step 1f: Install the wheel into pythonenv
    python_exe = ctx.pythonenv_python
    logger.info("Installing wheel into pythonenv (force-reinstall) ...")
    cmd = [
        str(python_exe), "-I", "-m", "pip", "install",
        "--no-cache-dir", "--no-deps", "--force-reinstall",
        "--progress-bar=off",
    ] + ctx.pip_mirror_args + [str(wheel_file)]
    rc = _run_pip_stream(cmd, "horn (install wheel)")
    if rc != 0:
        raise RuntimeError(f"Wheel install into pythonenv failed (exit code {rc})")
    logger.info("Project reinstalled into pythonenv")


def _precompile_src_horn(python_exe: Path, src_horn_dir: Path) -> None:
    """Pre-compile src/horn/ .py -> .pyc (legacy) before wheel build."""
    if not src_horn_dir.exists():
        logger.warning("src/horn/ not found: %s", src_horn_dir)
        return

    py_count = sum(1 for _ in src_horn_dir.rglob("*.py"))
    if py_count == 0:
        logger.warning("No .py files in src/horn/, skipping pre-compile")
        return

    logger.info(
        "Pre-compiling %d .py files in src/horn/ -> .pyc (legacy) ...",
        py_count,
    )

    script = f"""\
import compileall, sys
ok = compileall.compile_dir(
    r'{src_horn_dir}',
    maxlevels=50, quiet=1, force=True,
    optimize=0, legacy=True, workers=10,
)
sys.exit(0 if ok else 1)
"""
    t0 = time.monotonic()
    result = subprocess.run(
        [str(python_exe), "-I", "-c", script],
        capture_output=True, text=True, check=False,
    )
    elapsed = time.monotonic() - t0

    if result.returncode != 0:
        logger.warning(
            "src/horn pre-compile failed (%.1fs): %s",
            elapsed, result.stderr.strip(),
        )
    else:
        pyc_count = sum(1 for _ in src_horn_dir.rglob("*.pyc"))
        logger.info(
            "Pre-compiled %d .pyc in src/horn/ (%.1fs)", pyc_count, elapsed,
        )


def _compile_horn_dir(python_exe: Path, horn_dir: Path) -> bool:
    """Compile all .py files in site-packages/horn/ to .pyc (legacy mode)."""
    py_count = sum(1 for _ in horn_dir.rglob("*.py"))
    if py_count == 0:
        logger.warning("No .py files found in %s, skipping compile", horn_dir)
        return False

    logger.info(
        "Compiling %d .py files in site-packages/horn/ -> .pyc (legacy) ...",
        py_count,
    )

    script = f"""\
import compileall, sys
success = compileall.compile_dir(
    r'{horn_dir}',
    maxlevels=50, quiet=1, force=True,
    optimize=0, legacy=True, workers=10,
)
sys.exit(0 if success else 1)
"""
    t0 = time.monotonic()
    result = subprocess.run(
        [str(python_exe), "-I", "-c", script],
        capture_output=True, text=True, check=False,
    )
    elapsed = time.monotonic() - t0

    if result.returncode != 0:
        logger.warning(
            "horn compile failed (%.1fs): %s", elapsed, result.stderr.strip()
        )
        return False
    logger.info("Compiled %d files in horn/ (%.1fs)", py_count, elapsed)
    return True


def _strip_horn_sources(horn_dir: Path) -> None:
    """Remove .py source files where a matching .pyc exists."""
    removed = 0
    kept = 0
    for py_file in horn_dir.rglob("*.py"):
        pyc_file = py_file.with_suffix(".pyc")
        if pyc_file.exists():
            py_file.unlink()
            removed += 1
        else:
            kept += 1
    logger.info(
        "horn strip: removed %d .py, kept %d .py (no .pyc)", removed, kept
    )


def _clean_horn_pycache(horn_dir: Path) -> None:
    """Remove all __pycache__ directories inside horn/."""
    removed = 0
    for pycache in horn_dir.rglob("__pycache__"):
        if pycache.is_dir():
            shutil.rmtree(pycache)
            removed += 1
    if removed:
        logger.info("Removed %d __pycache__ directories in horn/", removed)


def _strip_pycache_from_wheel(wheel_path: Path) -> None:
    """Remove __pycache__/ entries from a wheel (ZIP) in-place."""
    tmp_fd, tmp_path = tempfile.mkstemp(
        suffix=".whl", dir=str(wheel_path.parent),
    )
    os.close(tmp_fd)
    tmp_path = Path(tmp_path)

    removed = 0
    try:
        with zipfile.ZipFile(wheel_path, "r") as zin, \
             zipfile.ZipFile(tmp_path, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                if "__pycache__" in item.filename:
                    removed += 1
                    continue
                zout.writestr(item, zin.read(item.filename))
        if removed:
            wheel_path.unlink()
            tmp_path.rename(wheel_path)
            logger.info("Stripped %d __pycache__ entries from wheel", removed)
        else:
            tmp_path.unlink()
    except Exception:
        tmp_path.unlink(missing_ok=True)
        raise


def _clean_src_pyc(src_horn_dir: Path) -> None:
    """Remove .pyc files from src/horn/ after wheel build."""
    if not src_horn_dir.exists():
        return
    removed = 0
    for pyc in src_horn_dir.rglob("*.pyc"):
        pyc.unlink()
        removed += 1
    if removed:
        logger.info("Cleaned %d .pyc from src/horn/", removed)


def _trim_project_metadata(sp: Path) -> None:
    """Remove the project's .dist-info regenerated by force-reinstall."""
    removed = 0
    for dist_info in list(sp.glob("classroom_horn_backend-*.dist-info")):
        shutil.rmtree(dist_info)
        removed += 1
    if removed:
        logger.info("Trimmed %d project metadata entries", removed)


def _clean_scripts_dir(ctx: BuildContext) -> None:
    """Clean Scripts/ but preserve pip executables for post-deploy use."""
    scripts_dir = ctx.pythonenv_dir / "Scripts"
    if not scripts_dir.exists():
        return

    _KEEP_PATTERNS = {"pip.exe", "pip3.exe", "pip3.10.exe"}

    removed = 0
    kept = 0
    for item in list(scripts_dir.iterdir()):
        if item.name.lower() in _KEEP_PATTERNS:
            kept += 1
            continue
        if item.is_file():
            item.unlink()
            removed += 1
        elif item.is_dir():
            shutil.rmtree(item)
            removed += 1

    logger.info(
        "Cleaned Scripts/: removed %d items, kept %d pip executables",
        removed, kept,
    )


